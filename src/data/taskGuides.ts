export function getTaskGuide(taskId: string): TaskGuide | undefined {
  // 이월된 이슈(예: s1-3-r1)도 원본 ID(s1-3)의 가이드를 그대로 찾도록 처리
  const baseId = taskId.replace(/-r\d+$/, '');
  return TASK_GUIDES[baseId];
}
